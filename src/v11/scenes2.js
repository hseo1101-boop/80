// src/data/scenes-by-station.js — the same day, told from your own doorway
// The historic scenes most people meet are retold for the five stations most people hold: the apprentice
// or journeyman in a workshop, the day labourer, the servant in someone else's house, the shopkeeper, the
// farmhand, and the old. Each telling has its own people (the master, the mistress, the customer, the
// foreman), its own stakes and its own choices; the generic choices are hidden from those who get one.
function sceneRoleOf(s) {
  const r = sceneRoleBase(s);
  // In the village a day labourer or a servant works for a farm: they meet village scenes as farmhands.
  return (r === 'labor' || r === 'servant') && s.place.includes('농촌') ? 'farm' : r;
}
function sceneRoleBase(s) {
  const j = s.job || '';
  if (j === '은퇴') return 'elder';
  if (/노동자|날품|물장수|짐꾼/.test(j)) return 'labor';
  if (/하녀|하인|가정부|요리사/.test(j)) return 'servant';
  if (/자영업자|상인|점원|도매상|장수|판매원/.test(j)) return 'shop';
  if (/도제|직인|장인|작업장|직물|방적|제화|인쇄|재봉|공 보조|여공/.test(j)) return 'apprentice';
  if (/농부|소작|목동/.test(j)) return 'farm';
  return ageOf(s) >= 62 ? 'elder' : null;
}

